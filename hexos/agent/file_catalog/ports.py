"""Bordes de E/S del servicio; sustituibles sin parchear transporte ni base."""
from typing import Protocol


class FileReader(Protocol):
    def __call__(self, device: str | None, request: dict) -> dict: ...


class CatalogStore(Protocol):
    def publish(self, result: dict, roots: list[str]) -> dict: ...
    def search(self, **kwargs) -> dict: ...
    def locations(self, **kwargs) -> dict: ...
    def remember_browse(self, result: dict, path: str) -> None: ...
    def remember_locations(self, result: dict) -> None: ...
    def publish_directories(self, result: dict) -> str: ...
    def read_directories(self, snapshot_id: str) -> dict: ...
